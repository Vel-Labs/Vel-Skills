#!/usr/bin/env python3
"""Review and refresh the pinned copy of GoogleChrome/modern-web-guidance.

Usage:
    python3 refresh.py index
        Rebuild INDEX.md from the guides already in this skill.
    python3 refresh.py compare [REF]
        Download REF (default: the upstream default branch) into a temporary folder and
        list guides added, removed and changed against the pinned copy. Changes nothing.
    python3 refresh.py apply REF
        After a person has reviewed `compare`, replace guides/ and LICENSE with REF's
        copies and rebuild INDEX.md. Then update the review fields in SKILL.md.

Only markdown guides and the licence are copied. Upstream code (the npx CLI, its
telemetry and the legacy scanner) is never downloaded into the skill or run.
Downloads use `gh api` and are extracted with tarfile's "data" filter.
"""

import difflib
import filecmp
import re
import shutil
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

REPO = "GoogleChrome/modern-web-guidance"
SKILL = Path(__file__).resolve().parents[1]
GUIDES = SKILL / "guides"


def build_index() -> None:
    rows = []
    for path in sorted(GUIDES.rglob("*.md")):
        text = path.read_text(encoding="utf-8")
        title = next((l[2:].strip() for l in text.splitlines() if l.startswith("# ")), path.stem)
        body = re.sub(r"```.*?```", "", text, flags=re.S)
        para = next(
            (
                p.strip().replace("\n", " ")
                for p in body.split("\n\n")
                if p.strip() and not p.lstrip().startswith(("#", "-", "*", ">", "|", "<"))
            ),
            "",
        )
        first = re.split(r"(?<=[.!?])\s", para, maxsplit=1)[0][:220]
        rel = path.relative_to(GUIDES)
        rows.append(f"| `{rel.parent}` | [{rel.stem}](guides/{rel.as_posix()}) | {title} | {first} |")
    header = [
        "# Guide index",
        "",
        "Generated by `scripts/refresh.py index`. Pick guides by area and summary, then open",
        "the file. A guide that says `npx ... retrieve \"<id>\"` means: open the guide with",
        "that id from this table. Never run the command.",
        "",
        f"{len(rows)} guides.",
        "",
        "| Area | Guide id | Title | Summary |",
        "|---|---|---|---|",
    ]
    (SKILL / "INDEX.md").write_text("\n".join(header + rows) + "\n", encoding="utf-8")
    print(f"INDEX.md: {len(rows)} guides")


def download(ref: str, into: Path) -> Path:
    archive = into / "src.tgz"
    with archive.open("wb") as out:
        subprocess.run(["gh", "api", f"repos/{REPO}/tarball/{ref}"], stdout=out, check=True)
    with tarfile.open(archive) as tar:
        tar.extractall(into / "x", filter="data")
    root = next((into / "x").iterdir())
    print(f"Downloaded {REPO}@{ref} ({root.name})")
    return root


def compare(ref: str) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        new = download(ref, Path(tmp)) / "skills/modern-web-guidance/guides"
        old_files = {p.relative_to(GUIDES) for p in GUIDES.rglob("*.md")}
        new_files = {p.relative_to(new) for p in new.rglob("*.md")}
        added = sorted(new_files - old_files)
        removed = sorted(old_files - new_files)
        changed = sorted(
            f for f in old_files & new_files if not filecmp.cmp(GUIDES / f, new / f, shallow=False)
        )
        for label, items in (("Added", added), ("Removed", removed), ("Changed", changed)):
            print(f"{label}: {len(items)}")
            for item in items:
                print(f"  {item}")
        for item in changed[:20]:
            diff = difflib.unified_diff(
                (GUIDES / item).read_text().splitlines(),
                (new / item).read_text().splitlines(),
                f"pinned/{item}",
                f"{ref}/{item}",
                lineterm="",
                n=1,
            )
            print("\n".join(list(diff)[:60]))


def apply(ref: str) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        root = download(ref, Path(tmp))
        shutil.rmtree(GUIDES)
        shutil.copytree(root / "skills/modern-web-guidance/guides", GUIDES)
        shutil.copy2(root / "LICENSE", SKILL / "LICENSE")
    build_index()
    print("Now update source_ref, reviewed and review_due in SKILL.md.")


if __name__ == "__main__":
    command = sys.argv[1] if len(sys.argv) > 1 else "index"
    if command == "index":
        build_index()
    elif command == "compare":
        compare(sys.argv[2] if len(sys.argv) > 2 else "HEAD")
    elif command == "apply" and len(sys.argv) > 2:
        apply(sys.argv[2])
    else:
        sys.exit(__doc__)
