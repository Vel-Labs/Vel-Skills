#!/usr/bin/env python3
"""Rebuild SKILLS_INDEX.md and the skills table in README.md from skill frontmatter.

Usage:
    python3 build_index.py [--check]

Reads every skills/<group>/<name>/SKILL.md in the library this file belongs to.
The index shows when to use each skill, its origin, when it was last reviewed,
when the next review is due, and its notes (`metadata.notes`). README.md gets the
same rows between `<!-- skills-table:start -->` and `<!-- skills-table:end -->`.
With --check, exits 1 if either file is out of date instead of writing.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from skill_meta import skills_under  # noqa: E402

REPO = Path(__file__).resolve().parents[3]
SKILLS = REPO / "skills"


def cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def rows() -> list[tuple]:
    out = []
    for skill in skills_under(SKILLS):
        rel = skill.path.relative_to(REPO).as_posix()
        group = skill.path.parent.parent.name
        out.append((group, skill.name, rel, skill))
    return out


def index_text() -> str:
    lines = [
        "# Skills index",
        "",
        "Generated by `skills/meta/skill-review/build_index.py` from each skill's frontmatter.",
        "Do not edit by hand. **Next review** comes from `metadata.review-due`; an agent",
        "using a skill past that date tells you and offers to review it first.",
        "",
    ]
    current = None
    for group, name, rel, skill in rows():
        if group != current:
            current = group
            lines += [
                f"## {group}",
                "",
                "| Entry | When to use it | Origin | Reviewed | Next review | Notes |",
                "| --- | --- | --- | --- | --- | --- |",
            ]
        meta = skill.meta
        source = meta.get("source", "")
        origin = meta.get("origin", "not set")
        if origin in {"external", "adapted"} and source.startswith("http"):
            origin = f"[{origin}]({source})"
        lines.append(
            f"| [{group}/{name}]({rel}) | {cell(skill.description)} | {origin} "
            f"| {meta.get('reviewed', 'not yet')} | {meta.get('review-due', 'not set')} "
            f"| {cell(meta.get('notes', ''))} |"
        )
    out = []
    for line in lines:
        if line.startswith("## ") and out and out[-1] != "":
            out.append("")
        out.append(line)
    return "\n".join(out) + "\n"


def readme_text(readme: str) -> str:
    start, end = "<!-- skills-table:start -->", "<!-- skills-table:end -->"
    table = ["| Skill | Group | What it is for | Next review |", "| --- | --- | --- | --- |"]
    for group, name, rel, skill in rows():
        table.append(
            f"| [{name}]({rel}) | {group} | {cell(skill.description)} | {skill.meta.get('review-due', 'not set')} |"
        )
    block = start + "\n" + "\n".join(table) + "\n" + end
    if start in readme and end in readme:
        before = readme[: readme.index(start)]
        after = readme[readme.index(end) + len(end) :]
        return before + block + after
    return readme.rstrip("\n") + "\n\n" + block + "\n"


def main() -> int:
    check = "--check" in sys.argv
    targets = {
        REPO / "SKILLS_INDEX.md": index_text(),
        REPO / "README.md": readme_text((REPO / "README.md").read_text(encoding="utf-8")),
    }
    stale = [p.name for p, text in targets.items() if p.read_text(encoding="utf-8") != text]
    if check:
        if stale:
            print("Out of date: " + ", ".join(stale) + ". Run build_index.py.")
            return 1
        print("Index and README are current.")
        return 0
    for path, text in targets.items():
        path.write_text(text, encoding="utf-8")
    print(f"Wrote SKILLS_INDEX.md and README.md ({len(rows())} skills).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
